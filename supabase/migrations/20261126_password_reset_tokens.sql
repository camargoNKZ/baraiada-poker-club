-- Códigos de redefinição de senha gerados por um administrador dentro do site
-- (substitui o e-mail de "esqueci a senha"). Guarda só o hash SHA-256 do código.
create table if not exists public.password_reset_tokens (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  token_hash text not null unique,
  created_by uuid references auth.users(id),
  created_at bigint not null,
  expires_at bigint not null,
  used_at bigint
);

create index if not exists idx_password_reset_tokens_user on public.password_reset_tokens (user_id);

alter table public.password_reset_tokens enable row level security;
revoke all on public.password_reset_tokens from anon, authenticated;
