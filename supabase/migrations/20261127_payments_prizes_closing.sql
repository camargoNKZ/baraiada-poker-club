-- Pagamentos informados pelo jogador ("Já paguei"), com comprovante opcional.
create table if not exists public.payment_claims (
  id bigint generated by default as identity primary key,
  tournament_id integer not null references public.tournaments(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  profile_id uuid references public.player_profiles(user_id) on delete set null,
  amount integer not null check (amount > 0),
  method text not null default 'Pix',
  note text not null default '',
  receipt_path text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'rejected')),
  created_at bigint not null,
  resolved_at bigint,
  resolved_by uuid references auth.users(id),
  transaction_id bigint references public.financial_transactions(id) on delete set null
);
create index if not exists idx_payment_claims_tournament on public.payment_claims (tournament_id, status);
create index if not exists idx_payment_claims_player on public.payment_claims (player_id);
-- Um pagamento informado pendente por jogador.
create unique index if not exists idx_payment_claims_one_pending on public.payment_claims (player_id) where status = 'pending';
alter table public.payment_claims enable row level security;
revoke all on public.payment_claims from anon, authenticated;

