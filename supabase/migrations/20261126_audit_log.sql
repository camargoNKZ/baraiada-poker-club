-- Histórico de ações: quem fez o quê, quando e em qual torneio.
create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  tournament_id integer references public.tournaments(id) on delete set null,
  actor_id uuid references auth.users(id) on delete set null,
  actor_name text not null default '',
  action text not null,
  summary text not null,
  details jsonb not null default '{}'::jsonb,
  created_at bigint not null
);
create index if not exists idx_audit_log_created on public.audit_log (created_at desc);
create index if not exists idx_audit_log_tournament on public.audit_log (tournament_id, created_at desc);
alter table public.audit_log enable row level security;
revoke all on public.audit_log from anon, authenticated;
